export default function SocialIcon({ name, size = 18 }) {
  switch (name) {
    case 'github':
      return <GithubIcon size={size} />;
    case 'linkedin':
      return <LinkedinIcon size={size} />;
    case 'twitter':
      return <XIcon size={size} />;
    default:
      return <Mail size={size} />;
  }
}
